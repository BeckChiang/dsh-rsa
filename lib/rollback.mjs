// One-click rollback script.
//
// Swapping app.asar is the only risky step of the whole plugin: the live
// archive has to be overwritten while DSH is not running, and if that copy is
// interrupted the app does not start at all — and then the plugin, which lives
// inside the app, cannot help. So a standalone .cmd file is installed next to
// the plugin (inside its own directory) that restores app.asar.rsa-backup with
// no Node, no DSH and no plugin involved.
//
// The script is regenerated on every deploy with the resolved install paths
// baked in, so double-clicking it always targets the installation that was
// deployed, not a guessed one.

import path from "node:path";
import fs from "node:fs";
import { fileURLToPath } from "node:url";

const LIB_DIR = fileURLToPath(new URL("./", import.meta.url));
const BIN_DIR = path.join(LIB_DIR, "..", "bin");

export const ROLLBACK_FILE = "rsa-rollback.cmd";

/** Absolute path of the rollback script inside the plugin directory. */
export function rollbackPath(overrides = {}) {
  const dir = overrides.pluginDir ? path.join(String(overrides.pluginDir), "bin") : BIN_DIR;
  return path.join(dir, ROLLBACK_FILE);
}

/**
 * Build the rollback script body.
 * Kept pure ASCII: a .cmd is read with the console codepage, so UTF-8 Chinese
 * would show up as mojibake on a machine that is not in UTF-8 mode.
 */
export function rollbackScript({ resources, backup, asar, exe }) {
  const res = String(resources || "");
  const bak = String(backup || path.join(res, "app.asar.rsa-backup"));
  const live = String(asar || path.join(res, "app.asar"));
  const image = path.basename(String(exe || "DeepSeek Harness.exe"));
  return [
    "@echo off",
    "setlocal",
    "title DSH RSA rollback",
    "rem Restore the original app.asar saved by the dsh-rsa deep deployment.",
    "rem Generated by dsh-rsa; see the plugin README, section Rollback.",
    "",
    'set "RES=%~1"',
    'set "BAK=%~2"',
    'set "LIVE=%~3"',
    `if not defined RES set "RES=${res}"`,
    `if not defined BAK set "BAK=${bak}"`,
    `if not defined LIVE set "LIVE=${live}"`,
    "",
    'if not exist "%BAK%" goto nobackup',
    'if not exist "%LIVE%" goto nolive',
    "",
    `tasklist /fi "imagename eq ${image}" 2>nul | find /i "${image}" >nul`,
    "if not errorlevel 1 goto running",
    "",
    'echo Restoring backup to "%LIVE%" ...',
    'copy /y "%BAK%" "%LIVE%" >nul',
    "if errorlevel 1 goto copyfailed",
    "echo.",
    "echo [OK] app.asar restored. Start DeepSeek Harness again.",
    "echo The backup file is kept, so this script can be run again.",
    "echo.",
    "pause",
    "exit /b 0",
    "",
    ":running",
    "echo [STOP] DeepSeek Harness is still running.",
    "echo Close it completely (including the tray icon), then run this again.",
    "echo.",
    "pause",
    "exit /b 2",
    "",
    ":nobackup",
    'echo [STOP] No backup found at "%BAK%".',
    "echo The installation was never deployed by dsh-rsa, or the backup was removed.",
    "echo.",
    "pause",
    "exit /b 3",
    "",
    ":nolive",
    'echo [STOP] No app.asar at "%LIVE%".',
    "echo Pass the resources folder as the first argument:",
    "echo   rsa-rollback.cmd \"C:\\path\\to\\DeepSeek Harness\\resources\"",
    "echo.",
    "pause",
    "exit /b 4",
    "",
    ":copyfailed",
    "echo [STOP] The copy failed. Close DeepSeek Harness completely and retry;",
    "echo if it still fails, copy the backup over app.asar by hand.",
    "echo.",
    "pause",
    "exit /b 1",
    "",
  ].join("\r\n");
}

/**
 * Write (or refresh) the rollback script. Returns its absolute path; the file is
 * only written when the content actually changes so repeated deploys do not
 * churn the file timestamp.
 */
// The script is only meaningful for the installation that is actually running
// it, so a caller with throw-away paths (tests, dry runs run outside Electron)
// gets the path back without a 200 MB-install script being rewritten to point
// at a temp directory. callers inside the host either pass pluginDir or resolve
// to process.resourcesPath, which is exactly the real installation.
function targetsRealInstall(paths) {
  if (paths.pluginDir) return true;
  const real = process.resourcesPath;
  if (!real || !paths.resources) return false;
  try {
    return path.resolve(String(paths.resources)) === path.resolve(String(real));
  } catch {
    return false;
  }
}

export function ensureRollbackScript(paths = {}) {
  const target = rollbackPath(paths);
  if (!targetsRealInstall(paths)) return target;
  const body = rollbackScript(paths);
  try {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    if (fs.existsSync(target) && fs.readFileSync(target, "utf8") === body) return target;
    fs.writeFileSync(target, body, "utf8");
  } catch {
    // A read-only plugin directory must not break a deployment; the UI reports
    // the path either way and shows whether the file exists.
  }
  return target;
}

export function rollbackExists(overrides = {}) {
  try {
    return fs.existsSync(rollbackPath(overrides));
  } catch {
    return false;
  }
}
